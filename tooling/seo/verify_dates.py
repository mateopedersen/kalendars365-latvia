   if [(int(a),int(b)) for a,b in weeks]!=[(d.isocalendar().year,d.isocalendar().week) for d in [start+dt.timedelta(days=7*i) for i in range(6)]]:errors.append({'url':url,'problem':'ISO row labels mismatch'})
   checks+=3
